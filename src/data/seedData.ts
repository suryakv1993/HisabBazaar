export function getInitialHistory(): ProfitCalculationResult[] {
  const products = getInitialProducts();
  return products.map((p, idx) => {
    const calc = calculateProfit({
      productName: p.name,
      sku: p.sku,
      productCost: p.productCost,
      sellingPrice: p.sellingPrice,
      quantity: 1,
      gstRate: p.gstRate,
      marketplace: p.marketplace,
      commissionRate: p.commissionRate,
      fixedFee: p.fixedFee,
      shippingFee: p.shippingFee,
      paymentCollectionFeeRate: p.marketplace === 'shopify' ? 2.36 : 2.0,
      paymentCollectionFixedFee: 0,
      packagingCost: p.packagingCost,
      advertisingCost: p.advertisingCost,
      discount: 0,
      otherExpenses: p.otherExpenses,
      returnAllowanceRate: p.returnAllowanceRate,
    });
    calc.timestamp = Date.now() - (idx + 1) * 3600000 * 8;
    return calc;
  });
}
